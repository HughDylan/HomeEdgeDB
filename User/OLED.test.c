/* 设置光标位置 (x: 0-127, y: 0-7行) */
void OLED_SetCursor(uint8_t x, uint8_t y) {
    OLED_WriteCmd(0xB0 + y);
    OLED_WriteCmd(((x & 0xF0) >> 4) | 0x10);
    OLED_WriteCmd(x & 0x0F);
}

/* 显示字符串 */
void OLED_ShowString(uint8_t Line, uint8_t Column, char *String) {
    uint8_t i;
    uint8_t x = (Column - 1) * 6;  // 每列 6 个像素宽
    uint8_t y = Line - 1;          // 页地址 (0-7)
    
    OLED_SetCursor(x, y);
    for (i = 0; String[i] != '\0'; i++) {
        // 简单处理：只支持大写字母和数字，如果是小写字母，转成大写
        char c = String[i];
        if (c >= 'a' && c <= 'z') c -= 32; 
        
        // 减去 32 是因为字库从空格 (ASCII 32) 开始
        if (c >= 32 && c <= 90) {
            for (uint8_t j = 0; j < 6; j++) {
                OLED_WriteData(F6x8[c - 32][j]);
            }
        }
    }
}
